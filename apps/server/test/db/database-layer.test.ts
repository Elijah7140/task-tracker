const backups = (folder: string) =>
  readdirSync(folder).filter((name) => /^tasktracker-.*\.db\.bak$/.test(name));
function singleBackup(folder: string) {
  const [saved, ...others] = backups(folder);
  assert.ok(saved);
  expect(others).toEqual([]);
  return saved;
}

const history = (path: string) =>
  query(path, "SELECT * FROM __EFMigrationsHistory ORDER BY MigrationId");
const ledger = (path: string) =>
  query(path, "SELECT migration_id, name FROM effect_sql_migrations ORDER BY migration_id");

function query(path: string, statement: string, ...parameters: SQLInputValue[]) {
  using database = new DatabaseSync(path, { readOnly: true });
  return database.prepare(statement).all(...parameters);
}

function execute(path: string, statement: string) {
  using database = new DatabaseSync(path);
  database.exec(statement);
}

function schema(path: string) {
  return query(
    path,
    `SELECT type, name, tbl_name, sql FROM sqlite_schema
    WHERE name NOT IN ('__EFMigrationsHistory', '__EFMigrationsLock', 'effect_sql_migrations')
      AND name NOT LIKE 'sqlite_autoindex___EFMigrations%'
    ORDER BY name`,
  ).map((row) => ({
    ...row,
    sql: typeof row.sql === "string" ? row.sql.trim().replace(/\s+/g, " ") : row.sql,
  }));
}

/** Leaves out what the Effect-only tickets and notes (§7.19) and in-progress (§7.18) stages add or alter. */
function withoutLaterStages(objects: ReadonlyArray<Readonly<Record<string, unknown>>>) {
  return objects.filter(
    (object) =>
      !["Project", "TodoItem", "StatusLevel"].includes(String(object["name"])) &&
      !String(object["tbl_name"]).startsWith("Ticket") &&
      // Stage 16 rebuilds the full-text table and its triggers with a Notes column.
      !String(object["name"]).startsWith("TodoItemSearch"),
  );
}

function snapshot(path: string) {
  return query(
    path,
    "SELECT name FROM sqlite_schema WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name != 'effect_sql_migrations'",
  ).map(({ name }) => {
    using database = new DatabaseSync(path, { readOnly: true });
    const statement = database.prepare(`SELECT * FROM "${String(name)}"`);
    statement.setReadBigInts(true);
    return [name, statement.all()] as const;
  });
}

/** Columns a later migration drops, which the adopted rows no longer have (§7.4). */
const droppedColumns: Readonly<Record<string, readonly string[]>> = {
  TodoItem: ["ScheduledStart", "ScheduledEnd"],
};

function withoutDropped(table: string, row: Readonly<Record<string, unknown>>) {
  const dropped = droppedColumns[table] ?? [];
  return Object.fromEntries(Object.entries(row).filter(([name]) => !dropped.includes(name)));
}

/** Tables whose ToDo rows move Description into Notes at stage 16 (§7.19). */
const notesTables = new Set(["TodoItem", "TodoItemSearch"]);

/** The full-text shadow tables, which stage 16 rebuilds with a Notes column (§7.2). */
const isSearchShadow = (table: string) => table.startsWith("TodoItemSearch_");

/** An adopted row as stage 16 leaves it: a ToDo's Description is its Notes (§7.19). */
function withNotes(table: string, row: Readonly<Record<string, unknown>>) {
  if (!notesTables.has(table) || row["ItemKind"] === "Ticket") {
    return row;
  }
  return { ...row, Description: null, Notes: row["Description"] };
}

function expectOriginalRows(path: string, before: ReturnType<typeof snapshot>) {
  for (const [table, original] of before) {
    if (isSearchShadow(String(table))) {
      continue;
    }
    const rows = original.map((row) =>
      withNotes(String(table), withoutDropped(String(table), row)),
    );
    const [first] = rows;
    if (!first) {
      continue;
    }
    const columns = Object.keys(first)
      .map((name) => `"${name}"`)
      .join(", ");
    const expected =
      table === "FieldDefinition"
        ? rows.map((row) => (row["Key"] === "status" ? { ...row, Key: "status-2" } : row))
        : rows;
    using database = new DatabaseSync(path, { readOnly: true });
    const statement = database.prepare(`SELECT ${columns} FROM "${String(table)}"`);
    statement.setReadBigInts(true);
    expect(statement.all()).toEqual(expected);
  }
}

