using TaskTracker.Infrastructure.Tests.AutoGenerated;

namespace TaskTracker.Infrastructure.Tests;

internal static class FixtureCommand
{
    private const string FixtureFilter = "FullyQualifiedName~GenerateEfFixtures";
    private const string FixtureMethod = "*.GenerateEfFixtures";

    internal static bool PublishFixtures => Environment.GetCommandLineArgs()
        .Any(static arg => arg is FixtureFilter or FixtureMethod);

    public static int Main(string[] args)
    {
        // The migration guide uses VSTest syntax. Translate only the fixture command for xUnit's MTP runner.
        for (var index = 0; index + 1 < args.Length; index++)
        {
            if (args[index] == "--filter" && args[index + 1] == FixtureFilter)
            {
                args[index] = "--filter-method";
                args[index + 1] = FixtureMethod;
                break;
            }
        }

        return XunitAutoGeneratedEntryPoint.Main(args);
    }
}